/** Engraving font in the XY plane. Build with the specified physical stroke width. */
export function strokeLabel(
  text: string, height: number, maxWidth: number, stroke: number, z: number,
): THREE.BufferGeometry | null {
  const characters = text.toUpperCase().trim();
  if (!characters.length) return null;
  const width = Math.min(height * 0.68, (maxWidth - stroke) / (characters.length * 1.4 - 0.4));
  const advance = width * 1.4;
  let x = -(advance * characters.length - width * 0.4) / 2;
  const letters: THREE.BufferGeometry[] = [];
  for (const character of characters) {
    const strokes: Stroke[] = FONT_GLYPHS[character] ??
      (character === '+' ? [[[0, 0.5], [1, 0.5]], [[0.5, 0.15], [0.5, 0.85]]] :
      character === '.' ? [[[0.45, 0], [0.55, 0]]] :
      character === ' ' ? [] : FONT_GLYPHS['-']);
    let letter: THREE.BufferGeometry | null = null;
    for (const [[x1, y1], [x2, y2]] of strokes) {
      const dx = (x2 - x1) * width;
      const dy = (y2 - y1) * height;
      const piece = box(Math.hypot(dx, dy) + stroke, stroke, 0.55, 0, 0, z)
        .rotateZ(Math.atan2(dy, dx))
        .translate(x + (x1 + x2) * width / 2, ((y1 + y2) / 2 - 0.5) * height, 0);
      letter = letter ? booleanMesh(letter, piece, 'add') : piece;
    }
    if (letter) letters.push(letter);
    x += advance;
  }
  if (!letters.length) return null;
  const result = combine(letters);
  letters.forEach((letter) => letter.dispose());
  return result;
}
