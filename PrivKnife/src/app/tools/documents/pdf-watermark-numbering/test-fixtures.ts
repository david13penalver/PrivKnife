export interface SyntheticPdfOptions {
  rotationDeg?: 0 | 90 | 180 | 270;
  cropBoxInset?: number;
}

export async function createSyntheticPdf(
  pageCount: number = 3,
  opts: SyntheticPdfOptions = {}
): Promise<Uint8Array> {
  const pdfDoc = await PDFDocument.create();
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica);

  for (let i = 0; i < Math.max(1, pageCount); i++) {
    const page = pdfDoc.addPage([595.28, 841.89]);
    page.drawText(`Master Services Agreement - Page ${i + 1}`, {
      x: 50,
      y: 780,
      size: 16,
      font,
      color: rgb(0.1, 0.1, 0.1),
    });
    page.drawText('Clause 1. Confidentiality obligations apply across all exhibits.', {
      x: 50,
      y: 740,
      size: 11,
      font,
      color: rgb(0.25, 0.25, 0.25),
    });

    if (opts.rotationDeg) {
      page.setRotation(degrees(opts.rotationDeg));
    }

    if (opts.cropBoxInset && opts.cropBoxInset > 0) {
      const inset = opts.cropBoxInset;
      page.setCropBox(inset, inset, 595.28 - inset * 2, 841.89 - inset * 2);
    }
  }

  return pdfDoc.save({ useObjectStreams: false });
}

export async function createFakeEncryptedPdfBytes(): Promise<Uint8Array> {
  const pdfDoc = await PDFDocument.create();
  pdfDoc.addPage([200, 200]);
  const encDict = pdfDoc.context.obj({
    Filter: PDFName.of('Standard'),
    V: PDFNumber.of(4),
    R: PDFNumber.of(4),
    Length: PDFNumber.of(128),
  });
  const encRef = pdfDoc.context.register(encDict);
  pdfDoc.context.trailerInfo.Encrypt = encRef;
  return pdfDoc.save({ useObjectStreams: false });
}

export function createCorruptPdfBytes(): Uint8Array {
  return Uint8Array.from(
    '%PDF-1.7\n%%CORRUPTED_MISSING_PAGE_TREE',
    (ch) => ch.charCodeAt(0)
  );
}

export function createInvalidImageBytes(): Uint8Array {
  return Uint8Array.from('NOT_A_VALID_PNG_OR_JPEG', (ch) => ch.charCodeAt(0));
}
