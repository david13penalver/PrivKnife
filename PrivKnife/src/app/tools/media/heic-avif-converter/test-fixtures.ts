export function createSyntheticHeicFile(
  name: string,
  mimeType: string = 'image/heic'
): File {
  // Valid ISO-BMFF ftyp box header (24 bytes)
  const ftypHeader = new Uint8Array([
    0x00, 0x00, 0x00, 0x18, // box size = 24
    0x66, 0x74, 0x79, 0x70, // 'ftyp'
    0x68, 0x65, 0x69, 0x63, // 'heic' major brand
    0x00, 0x00, 0x00, 0x00, // minor version = 0
    0x6d, 0x69, 0x66, 0x31, // 'mif1'
    0x68, 0x65, 0x69, 0x63, // 'heic'
  ]);

  // Valid 1x1 JPEG embedded preview payload
  const tinyJpeg = new Uint8Array([
    0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01,
    0x01, 0x01, 0x00, 0x48, 0x00, 0x48, 0x00, 0x00, 0xff, 0xdb, 0x00, 0x43,
    0x00, 0x08, 0x06, 0x06, 0x07, 0x06, 0x05, 0x08, 0x07, 0x07, 0x07, 0x09,
    0x09, 0x08, 0x0a, 0x0c, 0x14, 0x0d, 0x0c, 0x0b, 0x0b, 0x0c, 0x19, 0x12,
    0x13, 0x0f, 0x14, 0x1d, 0x1a, 0x1f, 0x1e, 0x1d, 0x1a, 0x1c, 0x1c, 0x20,
    0x24, 0x2e, 0x27, 0x20, 0x22, 0x2c, 0x23, 0x1c, 0x1c, 0x28, 0x37, 0x29,
    0x2c, 0x30, 0x31, 0x34, 0x34, 0x34, 0x1f, 0x27, 0x39, 0x3d, 0x38, 0x32,
    0x3c, 0x2e, 0x33, 0x34, 0x32, 0xff, 0xc0, 0x00, 0x0b, 0x08, 0x00, 0x01,
    0x00, 0x01, 0x01, 0x01, 0x11, 0x00, 0xff, 0xc4, 0x00, 0x1f, 0x00, 0x00,
    0x01, 0x05, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08,
    0x09, 0x0a, 0x0b, 0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f,
    0x00, 0xbf, 0x80, 0xff, 0xd9,
  ]);

  const mdatSize = tinyJpeg.length + 8;
  const mdatHeader = new Uint8Array([
    (mdatSize >> 24) & 0xff,
    (mdatSize >> 16) & 0xff,
    (mdatSize >> 8) & 0xff,
    mdatSize & 0xff,
    0x6d, 0x64, 0x61, 0x74, // 'mdat'
  ]);

  const combined = new Uint8Array(ftypHeader.length + mdatHeader.length + tinyJpeg.length);
  combined.set(ftypHeader, 0);
  combined.set(mdatHeader, ftypHeader.length);
  combined.set(tinyJpeg, ftypHeader.length + mdatHeader.length);

  return new File([combined], name, { type: mimeType });
}

export function createSyntheticFile(
  name: string,
  mimeType: string,
  byteSize: number = 1024
): File {
  // Use tiny valid PNG bytes padded to byteSize so browser decoders succeed
  const tinyPng = new Uint8Array([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d,
    0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
    0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4, 0x89, 0x00, 0x00, 0x00,
    0x0d, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0x64, 0xf8, 0xcf, 0x50,
    0x0f, 0x00, 0x03, 0x86, 0x01, 0x80, 0x5a, 0x34, 0x7d, 0x6b, 0x00, 0x00,
    0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
  ]);
  const size = Math.max(tinyPng.length, byteSize);
  const bytes = new Uint8Array(size);
  bytes.set(tinyPng, 0);
  return new File([bytes], name, { type: mimeType });
}

